"""Generate Revit C# macro source from the schedule database."""

import json
import math
from typing import Any

import pandas as pd


def _csharp_string(value: str) -> str:
    return json.dumps(value, ensure_ascii=True)


def _clean_text(value: Any) -> str:
    if value is None or pd.isna(value):
        return ""
    return str(value).strip()


def _get_schedules(
    family_groups_df: pd.DataFrame,
    families_df: pd.DataFrame,
    params_df: pd.DataFrame,
) -> tuple[list[dict[str, Any]], list[str]]:
    family_categories = {
        _clean_text(row.get("name")): _clean_text(row.get("category"))
        for _, row in families_df.iterrows()
        if _clean_text(row.get("name"))
    }
    parameter_defaults = {
        _clean_text(row.get("name")): {
            "header": _clean_text(row.get("header_text")),
            "width": row.get("grid_column_width", 1.0),
        }
        for _, row in params_df.iterrows()
        if _clean_text(row.get("name"))
    }
    schedules = []
    skipped = []

    for schedule_name, rows in family_groups_df.groupby("group_name", sort=False, dropna=False):
        name = _clean_text(schedule_name)
        if not name:
            skipped.append("A schedule entry has no schedule name.")
            continue

        schedule_families = [
            _clean_text(family_name)
            for family_name in rows.get("family_name", pd.Series(dtype=str))
        ]
        categories = [family_categories.get(family_name, "") for family_name in schedule_families]
        if not schedule_families or any(not category for category in categories):
            skipped.append(f"{name} (a family has no configured Revit category)")
            continue
        categories = set(categories)
        if len(categories) != 1:
            skipped.append(f"{name} (families span multiple Revit categories)")
            continue

        fields = []
        seen_parameters = set()
        field_error = None
        for _, row in rows.iterrows():
            parameter_name = _clean_text(row.get("parameter_name"))
            if not parameter_name or parameter_name in seen_parameters:
                continue
            seen_parameters.add(parameter_name)

            defaults = parameter_defaults.get(parameter_name, {})
            header = _clean_text(row.get("header_text_override"))
            if not header:
                header = defaults.get("header") or parameter_name

            width = row.get("grid_column_width_override")
            if width is None or pd.isna(width) or not str(width).strip():
                width = defaults.get("width", 1.0)
            if width is None or pd.isna(width) or not str(width).strip():
                width = 1.0
            try:
                width = float(width)
            except (TypeError, ValueError):
                field_error = (
                    f"{name} (column width for '{parameter_name}' is not a number)"
                )
                break
            if not math.isfinite(width) or width <= 0:
                field_error = (
                    f"{name} (column width for '{parameter_name}' must be greater than zero)"
                )
                break

            fields.append(
                {
                    "name": parameter_name,
                    "header": header,
                    "width_inches": width,
                    "width_feet": width / 12,
                }
            )

        if field_error:
            skipped.append(field_error)
            continue
        if not fields:
            skipped.append(f"{name} (no schedulable parameters are configured)")
            continue

        schedules.append({"name": name, "category": categories.pop(), "fields": fields})

    if not schedules and not skipped:
        skipped.append("No schedules are configured.")
    return schedules, skipped


def generate_schedule_macro_source(
    family_groups_df: pd.DataFrame,
    families_df: pd.DataFrame,
    params_df: pd.DataFrame,
) -> str:
    """Build a standalone partial-class C# source file for the Revit macro project."""
    schedules, skipped_schedules = _get_schedules(
        family_groups_df,
        families_df,
        params_df,
    )
    lines = [
        "// Generated by Revit Parameter Manager. Add this file to the Revit macro project.",
        "using Autodesk.Revit.DB;",
        "using Autodesk.Revit.UI;",
        "using System;",
        "using System.Linq;",
        "",
        "namespace GLoveMacros",
        "{",
        "    public partial class ThisApplication",
        "    {",
        "        public void CreateSchedulesFromDatabase()",
        "        {",
        "            UIDocument? uiDoc = ActiveUIDocument;",
        "            Document? doc = uiDoc?.Document;",
        "            if (doc == null)",
        "            {",
        '                TaskDialog.Show("Schedule Generator", "No active Revit document is open.");',
        "                return;",
        "            }",
        "",
        "            int createdCount = 0;",
        "            var skipped = new System.Collections.Generic.List<string>",
        "            {",
    ]
    lines.extend(
        f"                {_csharp_string(reason)},"
        for reason in skipped_schedules
    )
    lines.extend(
        [
            "            };",
            "",
        ]
    )

    for schedule_index, schedule in enumerate(schedules):
        name_literal = _csharp_string(schedule["name"])
        category_literal = _csharp_string(schedule["category"])
        lines.extend(
            [
                f"            // Schedule {schedule_index + 1}: {schedule['name']}",
                "            try",
                "            {",
                "                using Transaction tx = new Transaction(doc, "
                + _csharp_string(f"Create Schedule - {schedule['name']}")
                + ");",
                "                if (tx.Start() != TransactionStatus.Started)",
                "                {",
                f'                    skipped.Add({name_literal} + " (transaction could not start)");',
                "                }",
                "                else",
                "                {",
                "                    try",
                "                    {",
                "                        bool alreadyExists = new FilteredElementCollector(doc)",
                "                            .OfClass(typeof(ViewSchedule))",
                "                            .Cast<ViewSchedule>()",
                f"                            .Any(existing => string.Equals(existing.Name, {name_literal}, StringComparison.OrdinalIgnoreCase));",
                "                        if (alreadyExists)",
                "                        {",
                "                            tx.RollBack();",
                f'                            skipped.Add({name_literal} + " (a schedule with this name already exists)");',
                "                        }",
                "                        else",
                "                        {",
                "                            Category? category = doc.Settings.Categories.Cast<Category>()",
                f"                                .FirstOrDefault(candidate => string.Equals(candidate.Name, {category_literal}, StringComparison.OrdinalIgnoreCase));",
                "                            if (category == null)",
                "                            {",
                f'                                throw new InvalidOperationException("Revit category not found: " + {category_literal});',
                "                            }",
                "                            ViewSchedule schedule = ViewSchedule.CreateSchedule(doc, category.Id);",
                f"                            schedule.Name = {name_literal};",
                "                            ScheduleDefinition definition = schedule.Definition;",
            ]
        )

        for field_index, field in enumerate(schedule["fields"]):
            parameter_literal = _csharp_string(field["name"])
            header_literal = _csharp_string(field["header"])
            schedulable_field_name = f"schedulableField{field_index}"
            schedule_field_name = f"scheduleField{field_index}"
            lines.extend(
                [
                    f"                            SchedulableField? {schedulable_field_name} = definition.GetSchedulableFields()",
                    f"                                .FirstOrDefault(candidate => string.Equals(candidate.GetName(doc), {parameter_literal}, StringComparison.OrdinalIgnoreCase));",
                    f"                            if ({schedulable_field_name} == null)",
                    "                            {",
                    f'                                throw new InvalidOperationException("Schedulable parameter not found: " + {parameter_literal});',
                    "                            }",
                    f"                            ScheduleField {schedule_field_name} = definition.AddField({schedulable_field_name});",
                    f"                            {schedule_field_name}.ColumnHeading = {header_literal};",
                    f"                            {schedule_field_name}.GridColumnWidth = {field['width_feet']:.12g};",
                    "                            try",
                    "                            {",
                    f"                                {schedule_field_name}.HorizontalAlignment = ScheduleHorizontalAlignment.Center;",
                    "                            }",
                    "                            catch",
                    "                            {",
                    "                                // Match FormatAllSchedules: continue if a field cannot be centered.",
                    "                            }",
                ]
            )

        lines.extend(
            [
                "                            tx.Commit();",
                "                            createdCount++;",
                "                        }",
                "                    }",
                "                    catch (Exception ex)",
                "                    {",
                "                        if (tx.GetStatus() == TransactionStatus.Started)",
                "                        {",
                "                            tx.RollBack();",
                "                        }",
                f"                        skipped.Add({name_literal} + \": \" + ex.Message);",
                "                    }",
                "                }",
                "            }",
                "            catch (Exception ex)",
                "            {",
                f"                skipped.Add({name_literal} + \": \" + ex.Message);",
                "            }",
                "",
            ]
        )

    lines.extend(
        [
            '            string message = $"Created {createdCount} schedule(s).";',
            "            if (skipped.Count > 0)",
            "            {",
            '                message += "\\n\\nSkipped:\\n" + string.Join("\\n", skipped);',
            "            }",
            '            TaskDialog.Show("Schedule Generator", message);',
            "        }",
            "    }",
            "}",
            "",
        ]
    )
    return "\n".join(lines)
